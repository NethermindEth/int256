using System.Text;
using System.Text.Json;
using Mono.Cecil;
using Mono.Cecil.Cil;

internal static class LeanEmitter
{

    internal static (string Lean, List<object> Coverage) Generate(MethodDefinition[] methods, string entrySignature = MetadataValidation.EntrySignature, FeatureProfile? selectedProfile = null)
    {
        FeatureProfile profile = selectedProfile ?? FeatureProfile.Scalar;
        bool classifiedFamily = new[] { "Add", "Subtract", "AddOverflow", "SubtractUnderflow" }
            .Any(name => MetadataValidation.SelectedEntry(name) == entrySignature);
        StringBuilder lean = new("-- Generated by Extractor v5. DO NOT EDIT.\nimport CIL.SymbolicExecution\nimport CIL.ProfileEquivalence\nset_option maxRecDepth 8192\nnamespace Extracted\nopen CIL\n");
        lean.Append($"@[cil_code] def profile : FeatureProfile := {profile.Lean}\n");
        lean.Append("theorem profileValid : profile.Valid := by decide\n");
        Feature[] queried = methods.SelectMany(m => Reachability.Analyze(m, profile))
            .Where(i => i.OpCode.Code == Code.Call && i.Operand is MethodReference r && FeatureProfile.Getter(r) is not null)
            .Select(i => FeatureProfile.Getter((MethodReference)i.Operand)!.Value).Distinct().Order().ToArray();
        if (classifiedFamily && queried.Any(feature => !profile.ClassifiedQueries.Contains(feature)))
            throw new InvalidDataException("New feature query invalidates the declared behaviour classification");
        lean.Append($"def queriedFeatures : List Feature := [{string.Join(", ", queried.Select(FeatureProfile.LeanFeature))}]\n");
        if (classifiedFamily) lean.Append("theorem queriedFeaturesClassified : queriedFeatures.all (profile.classify.queries.contains ·) = true := by decide\n");
        FieldDefinition[] data = methods.SelectMany(m => Reachability.Analyze(m, profile))
            .Where(i => i.OpCode.Code == Code.Ldsflda)
            .Select(i => StaticData.Validate((FieldReference)i.Operand, methods[0].Module)).Distinct().ToArray();
        if (data.Length == 1)
            lean.Append($"def broadcastLookupData : List (BitVec 8) := {StaticData.LeanBytes(data[0])}\n");
        List<object> coverage = [];
        for (int methodIndex = 0; methodIndex < methods.Length; methodIndex++)
        {
            MethodDefinition m = methods[methodIndex];
            var instructions = m.Body.Instructions;
            HashSet<Instruction> reachable = Reachability.Analyze(m, profile);
            string symbol = $"method{methodIndex}";
            string returnsValue = m.ReturnType.FullName == "System.Void" ? "false" : "true";
            lean.Append($"@[cil_code] def {symbol}Index : Nat := {methodIndex}\n");
            string locals = string.Join(", ", m.Body.Variables.Select(v => v.VariableType.FullName switch
            {
                "System.UInt64" or "System.Int64" => ".i64 0",
                "Nethermind.Int256.UInt256" => ".v256 0",
                "System.Boolean" or "System.Int32" or "System.UInt32" => ".i32 0",
                string s when s.EndsWith("&", StringComparison.Ordinal) &&
                    (s is "Nethermind.Int256.UInt256&" or "System.UInt64&" || RuntimeModels.SupportedType(v.VariableType)) => ".nullRef",
                string s when RuntimeModels.SupportedType(v.VariableType) && s.StartsWith("System.Runtime.Intrinsics.Vector128`1<", StringComparison.Ordinal) => ".v128 0",
                string s when RuntimeModels.SupportedType(v.VariableType) && s.StartsWith("System.Runtime.Intrinsics.Vector256`1<", StringComparison.Ordinal) => ".v256 0",
                _ => throw new InvalidDataException($"Unsupported local type {v.VariableType.FullName}")
            }));
            if (!m.Body.InitLocals)
                locals = string.Join(", ", m.Body.Variables.Select(_ => ".unmodeled"));
            string aggregateLocals = string.Join(", ", m.Body.Variables.Where(v => v.VariableType.FullName == "Nethermind.Int256.UInt256").Select(v => v.Index));
            string aggregateArgs = string.Join(", ", m.Parameters.Where(p => p.ParameterType.FullName == "Nethermind.Int256.UInt256").Select(p => p.Index + (m.HasThis ? 1 : 0)));
            // Keep the body folded during execution simplification. Its fields
            // and concrete instruction fetches have separately checked equations.
            lean.Append($"def {symbol}Body : Method := {{\n  profile := profile\n  returnsValue := {returnsValue}\n  locals := [{locals}]\n  aggregateLocals := [{aggregateLocals}]\n  aggregateArgs := [{aggregateArgs}]\n  code := [\n");
            List<string> ops = [];
            List<string> lookups = [];
            for (int instructionIndex = 0; instructionIndex < instructions.Count; instructionIndex++)
            {
                Instruction i = instructions[instructionIndex];
                bool live = reachable.Contains(i);
                string op;
                op = live ? InstructionTranslation.Translate(i, m, methods, methodIndex, profile)
                    : $".unsupported {JsonSerializer.Serialize(i.ToString())}";
                ops.Add($"    {op}, -- IL_{i.Offset:x4}{(live ? "" : " (unreachable in the selected environment)")}");
                // Supply the type before elaborating anonymous constructors.
                // Otherwise each lookup repeats expensive deferred type inference.
                lookups.Add($"@[cil_code ↓] theorem {symbol}Instruction{instructionIndex} : " +
                    $"{symbol}Body.code[{instructionIndex}]? = some ({op} : Op) := by rfl\n");
            }
            lean.Append(string.Join("\n", ops));
            lean.Append("\n  ] }\n\n");
            lean.Append($"@[cil_code] theorem {symbol}Locals : {symbol}Body.locals = [{locals}] := by rfl\n");
            lean.Append($"@[cil_code] theorem {symbol}AggregateLocals : {symbol}Body.aggregateLocals = [{aggregateLocals}] := by rfl\n");
            lean.Append($"@[cil_code] theorem {symbol}AggregateArgs : {symbol}Body.aggregateArgs = [{aggregateArgs}] := by rfl\n");
            lean.Append($"@[cil_code] theorem {symbol}Profile : {symbol}Body.profile = profile := by rfl\n");
            lean.Append($"@[cil_code] theorem {symbol}Returns : {symbol}Body.returnsValue = {returnsValue} := by rfl\n");
            lean.Append($"@[cil_code] theorem {symbol}Length : {symbol}Body.code.length = {instructions.Count} := by rfl\n");
            lean.Append(string.Join("", lookups));
            lean.Append('\n');
            coverage.Add(new { method = m.FullName, reachable = reachable.Select(i => i.Offset).Order().ToArray(),
                excluded = instructions.Where(i => !reachable.Contains(i)).Select(i => i.Offset).ToArray() });
        }
        lean.Append($"def program : Program := [{string.Join(", ", Enumerable.Range(0, methods.Length).Select(i => $"method{i}Body"))}]\n");
        lean.Append("theorem programProfiles : program.map (·.profile) = List.replicate program.length profile := by rfl\n");
        if (classifiedFamily)
        {
            lean.Append("theorem programClassified : program.Classified profile.classify :=\n  program.classified_of_check profile.classify (by decide)\n");
            lean.Append("theorem profileExecution_eq (p : FeatureProfile) (hp : p.Valid) (hc : p.classify = profile.classify)\n" +
                "    (fuel method : Nat) (args : List Value) (memory : Memory) :\n" +
                "    invoke program fuel method args memory = invoke (reprofile program p) fuel method args memory :=\n" +
                "  invoke_same_family_eq program p profile hp profileValid hc\n" +
                "    (uniform_of_profile_map program profile programProfiles) programClassified fuel method args memory\n");
        }
        else
        {
            lean.Append("theorem profileExecution_eq (p : FeatureProfile) (ha : program.ProfileAgreement profile p)\n" +
                "    (fuel method : Nat) (args : List Value) (memory : Memory) :\n" +
                "    invoke program fuel method args memory = invoke (reprofile program p) fuel method args memory :=\n" +
                "  invoke_uniform_reprofile_eq program profile p\n" +
                "    (uniform_of_profile_map program profile programProfiles) ha fuel method args memory\n");
        }
        for (int methodIndex = 0; methodIndex < methods.Length; methodIndex++)
        {
            string symbol = $"method{methodIndex}";
            lean.Append($"@[cil_code] theorem {symbol}Member : program[{methodIndex}]? = some {symbol}Body := by rfl\n");
            int bound = methods.Skip(methodIndex).Sum(m => Reachability.Analyze(m, profile).Count) + 1;
            lean.Append($"@[cil_code] theorem {symbol}Bound : executionBound program {methodIndex} = {bound} := by rfl\n");
        }
        int entryIndex = Array.FindIndex(methods, m => m.FullName == entrySignature);
        if (entryIndex < 0) throw new InvalidDataException("Public entry missing from discovered dependencies");
        lean.Append($"@[cil_code] def entryIndex := method{entryIndex}Index\n@[cil_code] def entryBody := method{entryIndex}Body\n");
        foreach (var group in methods.Select((method, index) => new { Role = MetadataValidation.Role(method, entrySignature), Index = index })
                     .Where(candidate => candidate.Role is not null).GroupBy(candidate => candidate.Role))
        {
            // Ambiguous candidates simply receive no optional role; raw stepping
            // remains available and extraction does not reject a decomposition.
            if (group.Count() != 1) continue;
            int index = group.Single().Index;
            lean.Append($"@[cil_code] def {group.Key}Index := method{index}Index\n");
            lean.Append($"@[cil_code] def {group.Key}Body := method{index}Body\n");
        }
        if (!classifiedFamily)
        {
            // Every compatible body is offered, without prescribing names or decomposition.
            // A mathematical summary is usable only after its actual body is proved.
            int[] candidates = methods.Select((method, index) => new { Method = method, Index = index })
                .Where(candidate => candidate.Method.IsStatic &&
                    candidate.Method.DeclaringType.FullName == "Nethermind.Int256.UInt256" &&
                    candidate.Method.ReturnType.FullName == "System.Void" &&
                    candidate.Method.Parameters.Count == 3 &&
                    candidate.Method.Parameters.All(parameter => parameter.ParameterType.FullName == MetadataValidation.UInt256Reference) &&
                    candidate.Method.Parameters[0].IsIn && !candidate.Method.Parameters[0].IsOut &&
                    candidate.Method.Parameters[1].IsIn && !candidate.Method.Parameters[1].IsOut &&
                    candidate.Method.Parameters[2].IsOut && !candidate.Method.Parameters[2].IsIn)
                .Select(candidate => candidate.Index).ToArray();
            lean.Append($"def limbProductCandidates : List Nat := [{string.Join(", ", candidates)}]\n");
            int[] storageCandidates = methods.Select((method, index) => new { Method = method, Index = index })
                .Where(candidate => MetadataValidation.Role(candidate.Method, entrySignature) == "storeLimbs")
                .Select(candidate => candidate.Index).ToArray();
            lean.Append($"def storageCandidates : List Nat := [{string.Join(", ", storageCandidates)}]\n");
        }
        lean.Append("end Extracted\n");
        return (lean.ToString(), coverage);
    }
}
